#!/usr/bin/env python3
"""Regenerate data/giscus.yaml: post path -> GitHub discussion number.

giscus normally finds a post's discussion through GitHub's discussion search
index (repo:... in:title "<path>"), which returns no results for this
repository. Pinning each post to its discussion number makes giscus fetch the
thread directly via `discussion(number:)` instead of searching.

Duplicate threads for the same path are resolved to the thread with the most
activity (comments + reactions), newest wins on a tie. The generator only ever
emits threads that currently exist, so a deleted thread falls back to pathname
mapping on the next run.
"""

import json
import shutil
import subprocess
import sys
from pathlib import Path

OWNER = "justinmklam"
REPO = "personal-blog"
CATEGORY = "Blog Comments"
CONTENT = Path("content/posts")
OUTPUT = Path("data/giscus.yaml")

QUERY = """
query($owner: String!, $name: String!) {
  repository(owner: $owner, name: $name) {
    discussions(first: 100) {
      pageInfo { hasNextPage }
      nodes {
        number
        title
        createdAt
        category { name }
        comments { totalCount }
        reactions { totalCount }
      }
    }
  }
}
"""


def warn(message):
    print(f"WARN {message}", file=sys.stderr)


def fail(message):
    sys.exit(f"error: {message}")


def fetch_discussions():
    if shutil.which("gh") is None:
        fail("gh CLI not found; install it and run 'gh auth login'")

    result = subprocess.run(
        [
            "gh",
            "api",
            "graphql",
            "-f",
            f"query={QUERY}",
            "-f",
            f"owner={OWNER}",
            "-f",
            f"name={REPO}",
        ],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        fail(f"gh api graphql failed:\n{result.stderr.strip()}")

    try:
        payload = json.loads(result.stdout)
    except json.JSONDecodeError as exc:
        fail(f"could not parse GitHub response: {exc}")

    if "errors" in payload:
        fail(f"GitHub returned errors: {payload['errors']}")

    discussions = payload["data"]["repository"]["discussions"]
    if discussions["pageInfo"]["hasNextPage"]:
        warn("more than 100 discussions; only the first 100 were mapped")

    return [d for d in discussions["nodes"] if d["category"]["name"] == CATEGORY]


def post_page_keys():
    """Map every post file to the path giscus sees as its pathname term."""
    if not CONTENT.is_dir():
        fail("run from the repository root (content/posts not found)")

    keys = set()
    for path in CONTENT.rglob("*.md"):
        relative = path.relative_to(CONTENT)
        if any(part.startswith(".") for part in relative.parts):
            continue
        key = f"posts/{relative.as_posix()}"
        if key.endswith("/index.md"):
            key = key[: -len("index.md")]
        else:
            key = f"{key[:-len('.md')]}/"
        keys.add(key.strip("/"))
    return keys


def resolve(discussions, page_keys):
    """Keep one discussion per page: most comments+reactions, newest on a tie."""
    best = {}
    for discussion in discussions:
        number = discussion["number"]
        key = discussion["title"].strip("/")
        if key not in page_keys:
            warn(f"unmatched discussion {number} {discussion['title']}")
            continue

        score = discussion["comments"]["totalCount"] + discussion["reactions"]["totalCount"]
        winner = best.get(key)
        if winner and (winner["score"], winner["createdAt"]) >= (score, discussion["createdAt"]):
            warn(f"duplicate {key}: kept {winner['number']} dropped {number}")
            continue
        if winner:
            warn(f"duplicate {key}: kept {number} dropped {winner['number']}")
        best[key] = {
            "number": number,
            "score": score,
            "createdAt": discussion["createdAt"],
        }
    return best


def write_mapping(best):
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Generated by `make giscus-map`; do not edit by hand.",
        "# giscus resolves by discussion number; GitHub's discussion search index is empty for this repo.",
    ]
    lines += [f"{key}: {best[key]['number']}" for key in sorted(best)]
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(best)} mapping(s) to {OUTPUT}", file=sys.stderr)


def main():
    discussions = fetch_discussions()
    write_mapping(resolve(discussions, post_page_keys()))


if __name__ == "__main__":
    main()
